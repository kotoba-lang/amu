#!/usr/bin/env python3
"""The x86_64-aiueos-user-plc-v1 target: raw cap-call against a declared set, in the PLC ELF layout (KOTOBA-175, ADR 0402).

Compiles with a native Amu compiler and checks the bytes (Python stages sources and observes; it emits nothing):

* the AIUEOS PLC program kotoba's compile-plc-st.py generates for plc/examples/motor.st (capabilities 16..19) compiles
  to the pinned ELF, and that ELF passes PLC_USER_ELF_VALID, a line-for-line replica of kotoba's
  os/aiueos/kotoba/plc-user-elf-valid.kotoba, and the trampoline/context checks of make-plc-native-receipt.py;
* every cap-call site is the ADR 0402 sequence (bitmap bt, ud2, trampoline call, r9 reload), one per source call;
* the context bitmap is exactly the declared set (also 0 and 63 at the word's two ends);
* refusals, each with no artifact: an undeclared capability (E7101), a capability that is not a literal on every path
  -- a parameter, a computed value, a value merged from branches, 64 -- (E7109), a wrong arity (E2103), a
  redefinition of cap-call (E2001), typed-cap-call (E7101), malformed --capabilities lists (E7109);
* negative controls of the validator replica: the motor ELF with a superset bitmap, a 0x220000 entry, the data
  segment moved, or fuel 256 is rejected;
* unchanged: user-v1's scalar ELF keeps its pinned SHA-256 and check-aiueos-user-elf-native.verify; the same source
  under the PLC target has the same code and differs only in the layout words.

Not shown here: execution. kotoba's AIUEOS_PLC_RT_SMOKE runs the program at CPL3 under QEMU.
"""

import argparse
import hashlib
import importlib.util
import json
import re
import struct
from pathlib import Path

HERE = Path(__file__).parent
TARGET = "x86_64-aiueos-user-plc-v1"
CAPS = "16,17,18,19"
# kotoba os/aiueos/scripts/compile-plc-st.py output for plc/examples/motor.st (kotoba f03105d2), byte for byte
MOTOR = """(ns aiueos.plc.motor (:export [main]))

;; Generated by compile-plc-st.py. Do not interpret this source at runtime.
(defn plc-dint [value]
  (let [word (bit-and value 4294967295)]
    (if (>= word 2147483648) (- word 4294967296) word)))

(defn main []
  (let [plc-v-enable (not (= (cap-call 16 0) 0))
        plc-v-sensor (plc-dint (cap-call 16 1))
        plc-v-command (plc-dint (+ plc-v-sensor 1))
        plc-v-motoron (and plc-v-enable (< plc-v-command 100))
        stage-0 (cap-call 17 (+ (if plc-v-motoron 1 0) (* 0 4294967296)))
        stage-1 (cap-call 17 (+ (bit-and plc-v-command 4294967295) (* 1 4294967296)))
        stages-ok (and (= stage-0 1) (= stage-1 1))
        watchdog (if stages-ok (cap-call 19 1) 0)
        commit (if (= watchdog 1) (cap-call 18 2) 0)]
    (if (= commit 1) 1 0)))
"""
MOTOR_SHA256 = "c64e408abea5c2af86c4df1838138937da2abc7ab885aa129343268404d87e7c"
SCALAR_V1_SHA256 = "a4c9232290f5c172de67411a20bd292ad703865ce69f2fdb66136140508376f8"
H = "(ns t (:export [main]))\n"
REFUSALS = [
    ("undeclared", "16,17,18", MOTOR, "E7101 cap-call capability 19 is not declared"),
    ("parameter", "16", H + "(defn- f [x] (cap-call x 0))\n(defn main [] (f 16))\n", "E7109"),
    ("computed", "16", H + "(defn main [] (cap-call (+ 16 0) 0))\n", "E7109"),
    ("merged", "16,17", H + "(defn main [] (let [c (= 1 1)] (cap-call (if c 16 17) 0)))\n", "E7109"),
    ("sixty-four", "16", H + "(defn main [] (cap-call 64 0))\n", "E7109"),
    ("arity", "16", H + "(defn main [] (cap-call 16))\n", "E2103"),
    ("redefined", "16", H + "(defn- cap-call [a :i64 b :i64] :i64 7)\n(defn main [] (cap-call 16 0))\n", "E2001"),
    ("typed", "16", H + "(defn main [] :i64 (let [x (typed-cap-call :io/write :string :string \"d\")] 42))\n",
     "E7101"),
]
BAD_LISTS = ["16,16", "17,16", "016", "64", "16,", ",16", "a", "16 17", "1,,2"]
# rsi <- [id]; mov rax,[r9+16]; bt rax,rsi; jc +2; ud2; rdx <- [arg]; mov rdi,r9; mov eax,0x1e1020; call rax;
# mov r9,[rbp-8]
SITE = re.compile(rb"\x48\x8b\xb5....\x49\x8b\x41\x10\x48\x0f\xa3\xf0\x72\x02\x0f\x0b\x48\x8b\x95....\x4c\x89\xcf"
                  rb"\xb8\x20\x10\x1e\x00\xff\xd0\x4c\x8b\x4d\xf8", re.S)


def load(name):
    spec = importlib.util.spec_from_file_location(name.replace("-", "_"), HERE / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def plc_user_elf_valid(image):
    """kotoba os/aiueos/kotoba/plc-user-elf-valid.kotoba (kotoba_aiueos_user_elf_valid), check for check."""
    length = len(image)

    def u8(o):
        return image[o] if 0 <= o < length and o < 16384 else None

    def u16(o):
        return int.from_bytes(image[o:o + 2], "little") if o + 2 <= length else -1

    def u32(o):
        return int.from_bytes(image[o:o + 4], "little") if o + 4 <= length else -1

    def zero32(o):
        return u32(o) == 0

    def segment(base, flags, filesz):
        offset = 4096 if base == 64 else 8192
        address = 1970176 if base == 64 else 1974272
        return (u32(base) == 1 and u32(base + 4) == flags and u32(base + 8) == offset and zero32(base + 12)
                and u32(base + 16) == address and zero32(base + 20) and u32(base + 24) == address
                and zero32(base + 28) and u32(base + 32) == filesz and zero32(base + 36)
                and u32(base + 40) == filesz and zero32(base + 44) and u32(base + 48) == 4096
                and zero32(base + 52))

    def context_zero(index, end):
        return all(u8(i) == 0 for i in range(index, end))

    if length < 8280 or length > 12288:
        return False
    text_size = u32(96)
    return (u32(0) == 1179403647 and u8(4) == 2 and u8(5) == 1 and u8(6) == 1 and u16(16) == 2
            and u16(18) == 62 and u32(20) == 1 and u32(24) == 1970176 and zero32(28) and u32(32) == 64
            and zero32(36) and u16(52) == 64 and u16(54) == 56 and u16(56) == 2 and text_size > 0
            and text_size <= 4096 and text_size <= length - 4096 and segment(64, 5, text_size)
            and segment(120, 6, 88) and zero32(8192) and zero32(8196) and u32(8200) == 512
            and zero32(8204) and u32(8208) == 983040 and zero32(8212) and context_zero(8216, 8240)
            and u32(8240) == 1970208 and zero32(8244) and context_zero(8248, 8272) and zero32(8272)
            and zero32(8276))


def receipt_checks(image):
    """make-plc-native-receipt.py validate_elf's trampoline and context words."""
    words = struct.unpack_from("<11Q", image, 8192)
    return (words[0] == 0 and words[1] == 512 and words[2] == 0xF0000 and not any(words[3:6])
            and words[6] == 0x1E1020 and not any(words[7:])
            and image[0x1020:0x102c] == bytes([0xB8, 5, 0, 0, 0, 0x48, 0x8B, 0x7F, 0x50, 0x0F, 5, 0xC3]))


def main(compiler, output):
    gate = load("check-aiueos-user-macos-native")
    v1 = load("check-aiueos-user-elf-native")
    gate.verify_macho(compiler)
    output.mkdir(parents=True, exist_ok=False, mode=0o700)
    report = {"compiler": gate.pin(compiler)}

    def compile_case(name, source, caps, target=TARGET, expected=0):
        (output / f"{name}.kotoba").write_text(source)
        args = ["compile", f"{name}.kotoba", "--target", target]
        if caps is not None:
            args += ["--capabilities", caps]
        result = gate.native_run(compiler, output, *args, "--output", f"{name}.elf", expected=expected)
        return result, output / f"{name}.elf"

    _, elf = compile_case("motor", MOTOR, CAPS)
    image = elf.read_bytes()
    have = hashlib.sha256(image).hexdigest()
    if have != MOTOR_SHA256 or not plc_user_elf_valid(image) or not receipt_checks(image):
        raise ValueError(f"motor PLC ELF {have} is not the pinned image admitted by plc-user-elf-valid")
    text = image[4096:4096 + struct.unpack_from("<Q", image, 96)[0]]
    sites = len(SITE.findall(text))
    if sites != MOTOR.count("(cap-call ") or text.count(b"\x0f\x05") != 1:
        raise ValueError(f"motor: {sites} cap-call sites, {text.count(b'\x0f\x05')} syscall bytes")
    report["motor"] = {"sha256": have, "capCallSites": sites, "plcUserElfValid": True}

    mutants = {}
    for name, offset, value, width in (("superset-bitmap", 8208, 0x1F0000, 8), ("entry-0x220000", 24, 0x220000, 8),
                                       ("data-offset", 128, 12288, 8), ("fuel-256", 8200, 256, 8)):
        candidate = bytearray(image)
        candidate[offset:offset + width] = value.to_bytes(width, "little")
        if plc_user_elf_valid(bytes(candidate)):
            raise ValueError("plc-user-elf-valid replica admitted the mutant " + name)
        mutants[name] = "rejected"
    _, superset = compile_case("superset", MOTOR, "16,17,18,19,20")
    if plc_user_elf_valid(superset.read_bytes()) or struct.unpack_from("<Q", superset.read_bytes(), 8208)[0] != 0x1F0000:
        raise ValueError("a superset declaration did not give exactly its own bitmap")
    mutants["compiled-superset"] = "bitmap 0x1f0000, rejected"
    report["validatorNegativeControls"] = mutants

    bitmaps = {}
    for name, caps, mask in (("ends", "0,63", (1 << 63) | 1), ("one", "5", 32)):
        _, out = compile_case(name, H + "(defn main [] 1)\n", caps)
        word = struct.unpack_from("<Q", out.read_bytes(), 8208)[0]
        if word != mask:
            raise ValueError(f"declared {caps}: bitmap {word:#x}")
        bitmaps[caps] = hex(word)
    report["bitmaps"] = bitmaps

    refusals = {}
    for name, caps, source, diagnostic in REFUSALS:
        result, out = compile_case(name, source, caps, expected=1)
        message = (result.stdout + result.stderr).decode(errors="replace")
        if diagnostic not in message or out.exists():
            raise ValueError(f"{name}: expected {diagnostic} and no output: {message}")
        refusals[name] = diagnostic
    for index, caps in enumerate(BAD_LISTS):
        result, out = compile_case(f"list{index}", H + "(defn main [] 1)\n", caps, expected=2)
        if b"E7109 expected --capabilities" not in result.stderr or out.exists():
            raise ValueError(f"--capabilities {caps!r} was not refused")
        refusals[f"--capabilities {caps}"] = "E7109"
    result, out = compile_case("nolist", H + "(defn main [] 1)\n", None, expected=1)
    if out.exists():
        raise ValueError("the PLC target compiled without --capabilities")
    refusals["no --capabilities"] = "usage"
    report["refusals"] = refusals

    _, scalar = compile_case("scalar", v1.SOURCE, None, target="x86_64-aiueos-user-v1")
    v1.verify(scalar.read_bytes())
    if hashlib.sha256(scalar.read_bytes()).hexdigest() != SCALAR_V1_SHA256:
        raise ValueError("user-v1 scalar ELF changed")
    _, scalar_plc = compile_case("scalar-plc", v1.SOURCE, "16,17,18,19")
    a, b = scalar.read_bytes(), scalar_plc.read_bytes()
    # the same code: header words other than the addresses and the text size, the user-v1 text (the PLC text only
    # appends the unused cap-call stub after it), and the context other than fuel, bitmap and trampoline address
    size = struct.unpack_from("<Q", a, 96)[0]
    layout = {24, 80, 88, 96, 104, 136, 144}
    header = {o for o in range(0, 176, 8) if a[o:o + 8] != b[o:o + 8]}
    context = {o for o in range(0, 88, 8) if a[8192 + o:8200 + o] != b[8192 + o:8200 + o]}
    if (len(a) != len(b) or not plc_user_elf_valid(b) or header - layout or context - {8, 16, 48}
            or a[4096:4096 + size] != b[4096:4096 + size]):
        raise ValueError(f"PLC scalar differs from user-v1 beyond the layout: {sorted(header - layout)} {sorted(context)}")
    report["userV1"] = {"sha256": SCALAR_V1_SHA256, "plcHeaderWords": sorted(header), "plcContextWords": sorted(context)}
    (output / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print("PASS_AIUEOS_USER_PLC " + json.dumps(report, sort_keys=True), flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    main(args.compiler.resolve(strict=True), args.output.resolve())
