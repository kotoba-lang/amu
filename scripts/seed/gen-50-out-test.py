# build errors: code word out of range; code too long (OUT full); CODE-BYTES mismatch
def build_scen(name, writes, errcode, post=(), extra_checks=()):
    lets, cur = chain([("MM-ERR", 0), ("MM-ERR-POS", 0), ("MM-ERR-N", 0)] + writes)
    lets.append(f"M1 (ly-run {cur})")
    cur = "M1"
    if post:
        l3, cur = chain(list(post), start="M1", prefix="P", leaf=True)
        lets += l3
    lets.append(f"M2 (out-build {cur} (t-src))")
    ck = [(f"{name} ERR", "(vector-at M2 MM-ERR)", errcode)] + list(extra_checks)
    l2, cur2 = checks_block(ck, "M2", "b")
    lets += l2
    out.append(f"(defn- t-{name} [M0 :vector-i64] :vector-i64\n  (let [" + "\n        ".join(lets) + "]\n    " + cur2 + "))\n")
