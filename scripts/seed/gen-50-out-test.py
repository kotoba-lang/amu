def wrap(x):
    x &= (1 << 64) - 1
    return x - (1 << 64) if x >> 63 else x
def hsh(bs):
    h = 7
    for b in bs: h = wrap(h * 1000003 + b)
    return h
NAMES = "alpha-beta-main"            # the source string S: alpha 0..5, beta 6..10, main 11..15
SYMS = {1: (0, 5), 2: (11, 15), 3: (6, 10)}   # sym index -> span
FNS = {1: dict(sym=1, code=1, np=2, ex=1), 2: dict(sym=3, code=10, np=1, ex=0), 3: dict(sym=2, code=21, np=0, ex=1)}
NW = 40
