total = pos[3] + len(LITS[3])
code = bytearray()
for w in CODE: code += w.to_bytes(4, "little")
code += bytes(poff - len(code))
pool = bytearray(code)
for k in sorted(LITS):
    pool += bytes(pos[k] - len(pool)); pool += LITS[k]
assert len(pool) == total
