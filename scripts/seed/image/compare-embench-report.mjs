// BOOTSTRAP-TOOL. Analyse existing qualification JSON; never run in a compiler.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const root = resolve(process.argv[2] ?? '');
const read = p => readFileSync(`${root}/${p}`, 'utf8');
const hash = p => createHash('sha256').update(readFileSync(`${root}/${p}`)).digest('hex');
if (!read('status.txt').startsWith('PASS:')) throw new Error('No qualified quiet measurement');
const loads = read('run-load.tsv').trim().split('\n').map(l => Number(l.split('\t')[1]));
if (!loads.length || loads.some(x => !Number.isFinite(x) || x > 4)) throw new Error('Missing or loaded samples');
const labels = ['stage0', 'r6l', 'r6m'];
const data = Object.fromEntries(labels.map(l => [l, JSON.parse(read(`results/${l}/qualification.json`))]));
const median = xs => [...xs].sort((a,b) => a-b)[Math.floor(xs.length/2)];
const geomean = xs => Math.exp(xs.reduce((s,x) => s+Math.log(x),0)/xs.length);
const inventory = data.stage0.workloads.map(x => x.workload).sort();
for (const l of labels) {
  const d = data[l];
  if (d.runner.sha256 !== hash('runner') || d.compiler.sha256 !== hash(`images/${l}`)) throw new Error(`Artifact changed: ${l}`);
  if (JSON.stringify(d.workloads.map(x => x.workload).sort()) !== JSON.stringify(inventory) || inventory.length !== 19) throw new Error('Inventory mismatch');
  for (const w of d.workloads) {
    const base = data.stage0.workloads.find(x => x.workload === w.workload);
    if (w.source_sha256 !== base.source_sha256 || w.source_sha256 !== hash(`bench/embench/ports/${w.workload}.kotoba`)) throw new Error('Source mismatch');
    if (w.check_ns.length !== 5 || w.compile_ns.length !== 5 || w.execution.length !== 5 || w.execution.some(x => x.result !== 1 || x.calls !== 1 || x.warmupCalls !== 0)) throw new Error('Incomplete correctness/sample evidence');
  }
}
const rows = inventory.map(name => {
  const r = {workload:name};
  for (const l of labels) {
    const w = data[l].workloads.find(x => x.workload === name);
    r.fidelity = w.fidelity;
    r[`${l}_check_ms`] = median(w.check_ns)/1e6;
    r[`${l}_compile_ms`] = median(w.compile_ns)/1e6;
    r[`${l}_execute_ns`] = median(w.execution.map(x => x.elapsedNanoseconds));
    r[`${l}_execute_min_ns`] = Math.min(...w.execution.map(x => x.elapsedNanoseconds));
    r[`${l}_execute_max_ns`] = Math.max(...w.execution.map(x => x.elapsedNanoseconds));
    r[`${l}_code_bytes`] = w.raw_code_bytes;
  }
  return r;
});
const stats = selected => Object.fromEntries(labels.map(l => [l, {
  check_median_sum_ms: selected.reduce((s,r) => s+r[`${l}_check_ms`],0),
  compile_median_sum_ms: selected.reduce((s,r) => s+r[`${l}_compile_ms`],0),
  raw_code_sum_bytes: selected.reduce((s,r) => s+r[`${l}_code_bytes`],0),
  compile_speedup_vs_stage0_geomean: geomean(selected.map(r => r.stage0_compile_ms/r[`${l}_compile_ms`])),
  execute_speedup_vs_stage0_geomean: geomean(selected.map(r => r.stage0_execute_ns/r[`${l}_execute_ns`])),
  execute_speedup_vs_r6l_geomean: geomean(selected.map(r => r.r6l_execute_ns/r[`${l}_execute_ns`]))
}]));
const identicalCode = data.r6m.workloads.filter(w => w.raw_code_sha256 === data.r6l.workloads.find(x => x.workload === w.workload).raw_code_sha256).length;
const summary = {official_embench_score:false, samples:5, runner_sha256:hash('runner'), max_sampled_load:Math.max(...loads), r6l_r6m_identical_code_workloads:identicalCode, all_19:stats(rows), full_9:stats(rows.filter(r => r.fidelity === 'full-correctness-translation'))};
writeFileSync(`${root}/comparison.json`, JSON.stringify({summary, rows}, null, 2)+'\n');
const fields = Object.keys(rows[0]);
writeFileSync(`${root}/comparison.csv`, fields.join(',')+'\n'+rows.map(r => fields.map(k => r[k]).join(',')).join('\n')+'\n');
let report = '# Embench port comparison: r6l, r6m and stage-0\n\n';
report += `One common runner (${summary.runner_sha256}); five samples per command and export. Every sampled host load <= ${summary.max_sampled_load.toFixed(2)} (limit 4). All 19 correctness exports returned 1.\n\n`;
report += 'Compiler timings include process startup. Execution measures one correctness export call, with no warmup. Nine workloads are full correctness translations; ten are adapted probes. These are local port comparisons, not official Embench scores.\n\n';
report += `r6l and r6m generated byte-identical raw code for ${identicalCode}/19 workloads. Timing differences between identical outputs do not establish a generated-code improvement.\n\n`;
report += '| Compiler | Sum of check medians (ms) | Sum of compile medians (ms) | Execution speedup vs stage-0 (geomean) | Raw code sum (B) |\n|---|---:|---:|---:|---:|\n';
for (const l of labels) { const s=summary.all_19[l]; report += `| ${l} | ${s.check_median_sum_ms.toFixed(2)} | ${s.compile_median_sum_ms.toFixed(2)} | ${s.execute_speedup_vs_stage0_geomean.toFixed(3)}x | ${s.raw_code_sum_bytes} |\n`; }
report += '\nFull nine correctness translations only:\n\n| Compiler | Sum of compile medians (ms) | Compile speedup vs stage-0 (geomean) | Execution speedup vs stage-0 (geomean) |\n|---|---:|---:|---:|\n';
for (const l of labels) { const s=summary.full_9[l]; report += `| ${l} | ${s.compile_median_sum_ms.toFixed(2)} | ${s.compile_speedup_vs_stage0_geomean.toFixed(3)}x | ${s.execute_speedup_vs_stage0_geomean.toFixed(3)}x |\n`; }
for (const [title, key, unit, factor] of [['Compilation','compile_ms','ms',1],['Native execution','execute_ns','µs',1000],['Raw code size','code_bytes','B',1]]) {
  report += `\n## ${title}\n\n| Workload | stage-0 (${unit}) | r6l (${unit}) | r6m (${unit}) |\n|---|---:|---:|---:|\n`;
  for (const r of rows) report += `| ${r.workload} | ${labels.map(l => (r[`${l}_${key}`]/factor).toFixed(key === 'code_bytes' ? 0 : 2)).join(' | ')} |\n`;
}
report += '\nExecution sample ranges are preserved in comparison.csv/json. Short single-call microsecond measurements require particular care; use the full nine-workload aggregate as well as the all-port aggregate. Raw extraction sizes include the required prefix and are not the official Embench text-size metric. Compiler/image hashes and all raw samples are preserved in results/*/qualification.json.\n';
writeFileSync(`${root}/comparison.md`, report);
console.log(JSON.stringify(summary));
